-- Grain: one completed, analyzed conversation per source session_id.
CREATE TABLE IF NOT EXISTS fact_conversation (
  conversation_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id TEXT NOT NULL UNIQUE,
  started_date_key INTEGER NOT NULL REFERENCES dim_date(date_key),
  customer_key BIGINT NOT NULL REFERENCES dim_customer(customer_key),
  plan_key INTEGER NOT NULL DEFAULT 0 REFERENCES dim_plan(plan_key),
  intent_key INTEGER NOT NULL REFERENCES dim_intent(intent_key),
  reason_key INTEGER NOT NULL REFERENCES dim_reason(reason_key),
  resolution_key INTEGER NOT NULL REFERENCES dim_resolution(resolution_key),
  started_at TIMESTAMPTZ NOT NULL,
  ended_at TIMESTAMPTZ NOT NULL,
  duration_seconds NUMERIC(14,3) GENERATED ALWAYS AS (EXTRACT(EPOCH FROM (ended_at - started_at))) STORED,
  sentiment_start SMALLINT CHECK (sentiment_start BETWEEN -2 AND 2),
  sentiment_end SMALLINT CHECK (sentiment_end BETWEEN -2 AND 2),
  churn_risk NUMERIC(5,4) CHECK (churn_risk BETWEEN 0 AND 1),
  quality_correctness SMALLINT CHECK (quality_correctness BETWEEN 1 AND 5),
  quality_policy_compliance SMALLINT CHECK (quality_policy_compliance BETWEEN 1 AND 5),
  quality_tone SMALLINT CHECK (quality_tone BETWEEN 1 AND 5),
  quality_resolved BOOLEAN,
  kb_gap BOOLEAN NOT NULL,
  summary TEXT NOT NULL,
  analyzed_at TIMESTAMPTZ NOT NULL,
  CHECK (ended_at >= started_at),
  CHECK (analyzed_at >= ended_at),
  CHECK (started_date_key = EXTRACT(YEAR FROM started_at AT TIME ZONE 'UTC')::INTEGER * 10000
    + EXTRACT(MONTH FROM started_at AT TIME ZONE 'UTC')::INTEGER * 100
    + EXTRACT(DAY FROM started_at AT TIME ZONE 'UTC')::INTEGER)
);
CREATE INDEX IF NOT EXISTS idx_conversation_date ON fact_conversation(started_date_key);
CREATE INDEX IF NOT EXISTS idx_conversation_reason ON fact_conversation(reason_key);
CREATE INDEX IF NOT EXISTS idx_conversation_resolution ON fact_conversation(resolution_key);

-- Grain: one source audit_log row, including reads, denials, and pending proposals.
-- session_id is a shared source identifier, not a foreign key to another fact table.
CREATE TABLE IF NOT EXISTS fact_tool_call (
  tool_call_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  audit_id BIGINT NOT NULL UNIQUE,
  session_id TEXT NOT NULL,
  date_key INTEGER NOT NULL REFERENCES dim_date(date_key),
  customer_key BIGINT NOT NULL DEFAULT 0 REFERENCES dim_customer(customer_key),
  tool_key INTEGER NOT NULL REFERENCES dim_tool(tool_key),
  reason_key INTEGER REFERENCES dim_reason(reason_key),
  policy_key INTEGER REFERENCES dim_policy(policy_key),
  offer_key INTEGER REFERENCES dim_offer(offer_key),
  occurred_at TIMESTAMPTZ NOT NULL,
  result_status TEXT NOT NULL CHECK (result_status IN ('done','pending_confirmation','denied','needs_human','error')),
  autonomy_level TEXT NOT NULL CHECK (autonomy_level IN ('read','auto','confirm','human_only')),
  actor TEXT NOT NULL CHECK (actor IN ('agent','human','system')),
  error_code TEXT,
  args_json JSONB NOT NULL CHECK (jsonb_typeof(args_json) = 'object'),
  payment_id TEXT,
  refunded_amount NUMERIC(10,2),
  currency TEXT,
  CHECK (date_key = EXTRACT(YEAR FROM occurred_at AT TIME ZONE 'UTC')::INTEGER * 10000
    + EXTRACT(MONTH FROM occurred_at AT TIME ZONE 'UTC')::INTEGER * 100
    + EXTRACT(DAY FROM occurred_at AT TIME ZONE 'UTC')::INTEGER),
  CHECK ((refunded_amount IS NULL AND currency IS NULL) OR
    (refunded_amount IS NOT NULL AND refunded_amount > 0 AND currency IS NOT NULL
     AND currency ~ '^[A-Z]{3}$' AND payment_id IS NOT NULL AND result_status = 'done'))
);
CREATE INDEX IF NOT EXISTS idx_tool_call_session ON fact_tool_call(session_id);
CREATE INDEX IF NOT EXISTS idx_tool_call_date ON fact_tool_call(date_key);
-- Prevent repeated calls or reimports from attributing the same refund twice.
CREATE UNIQUE INDEX IF NOT EXISTS idx_tool_call_refunded_payment
  ON fact_tool_call(payment_id) WHERE refunded_amount IS NOT NULL;

-- A multivalued dimension bridge keeps policy citations from multiplying conversations.
CREATE TABLE IF NOT EXISTS bridge_conversation_policy (
  conversation_key BIGINT NOT NULL REFERENCES fact_conversation(conversation_key),
  policy_key INTEGER NOT NULL REFERENCES dim_policy(policy_key),
  PRIMARY KEY (conversation_key, policy_key)
);

-- Compatibility projection; the stored facts remain dimensional and typed.
CREATE OR REPLACE VIEW analysis AS
SELECT f.session_id, c.user_id, i.intent_code AS primary_intent,
       r.reason_code AS underlying_reason, f.sentiment_start, f.sentiment_end,
       f.churn_risk, res.resolution_code AS resolution,
       COALESCE((
         SELECT jsonb_agg(jsonb_build_object('audit_id', a.audit_id, 'tool', t.tool_name,
                                           'args', a.args_json) ORDER BY a.occurred_at, a.audit_id)
         FROM fact_tool_call a JOIN dim_tool t USING (tool_key)
         WHERE a.session_id = f.session_id AND a.result_status = 'done' AND t.is_state_changing
       ), '[]'::jsonb)::TEXT AS actions_json,
       COALESCE((
         SELECT jsonb_agg(p.policy_ref ORDER BY p.policy_ref)
         FROM bridge_conversation_policy b JOIN dim_policy p USING (policy_key)
         WHERE b.conversation_key = f.conversation_key
       ), '[]'::jsonb)::TEXT AS policy_refs_json,
       jsonb_build_object('correctness', f.quality_correctness, 'policy_compliance', f.quality_policy_compliance,
                          'tone', f.quality_tone, 'resolved', f.quality_resolved)::TEXT AS quality_json,
       f.kb_gap::INTEGER AS kb_gap, f.summary, f.analyzed_at
FROM fact_conversation f
JOIN dim_customer c USING (customer_key)
JOIN dim_intent i USING (intent_key)
JOIN dim_reason r USING (reason_key)
JOIN dim_resolution res USING (resolution_key);

COMMIT;
